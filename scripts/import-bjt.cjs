const PAIRS = ['**', '__', '~~', '##', '$$'];
const ENTITIES = { '&gt;': '>', '&lt;': '<', '&amp;': '&' };

/** Plain text of a BJT entry: markup and footnote pointers removed, line breaks kept as \n. */
function toPlain(s) {
  s = s || '';
  const parse = (start, end) => {
    let out = '';
    let i = start;
    while (i < end) {
      const two = s.substr(i, 2);
      if (PAIRS.includes(two)) {
        const close = s.indexOf(two, i + 2);
        if (close >= 0 && close + 2 <= end) { out += parse(i + 2, close); i = close + 2; } else { out += two; i += 2; }
        continue;
      }
      const ch = s[i];
      if (ch === '{') {
        const close = s.indexOf('}', i + 1);
        if (close > i + 1 && close < end && !s.slice(i + 1, close).includes('\n')) { i = close + 1; continue; }
      } else if (ch === '↴') { out += '\n'; i++; continue; }
      else if (ch === '<') {
        const m = /^<(\/?)(hr|b)\s*\/?>/i.exec(s.slice(i, Math.min(end, i + 8)));
        if (m) { if (m[2].toLowerCase() === 'hr') out += '\n'; i += m[0].length; continue; }
      } else if (ch === '&') {
        const ent = s.slice(i, i + 5).match(/^&(gt|lt|amp);/);
        if (ent) { out += ENTITIES[ent[0]]; i += ent[0].length; continue; }
      }
      out += ch;
      i++;
    }
    return out;
  };
  return parse(0, s.length);
}

const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const lines = (s) => s.split('\n').map((l) => l.replace(/\s+/g, ' ').trim()).filter((l, i, a) => l || (i > 0 && i < a.length - 1));
const normHeading = (s) => toPlain(s).replace(/[\[\]]/g, '').replace(/^\s*[\d.\s]+\s*/, '').replace(/[\s.]+$/, '').replace(/\s+/g, ' ').trim();
const isNumberLine = (s) => /^[\d.\s]+$/.test(toPlain(s).trim());

function entryHtml(e) {
  const text = lines(toPlain(e.text)).map(escapeHtml).join('<br />');
  if (!text) return '';
  if (e.type === 'heading') return `<p><strong>${text}</strong></p>`;
  if (e.type === 'gatha' || e.type === 'centered') return `<p style='text-align:center'>${text}</p>`;
  return `<p class='prose'>${text}</p>`; // left-aligned prose (see ContentContainer)
}

// ---------------------------------------------------------------- selection

async function loadFile(name) {
  const local = process.env.BJT_TEXT_DIR;
  if (local) return JSON.parse(fs.readFileSync(path.join(local, `${name}.json`), 'utf8'));
  const res = await fetch(`${SOURCE_BASE}/${name}.json`);
  if (!res.ok) throw new Error(`${name}.json: HTTP ${res.status}`);
  return res.json();
}

function flatten(file) {
  const out = [];
  for (const page of file.pages) {
    const pali = page.pali.entries;
    const sinh = page.sinh.entries;
    if (pali.length !== sinh.length) throw new Error(`${file.filename} page ${page.pageNum}: pali/sinh entry counts differ`);
    pali.forEach((p, i) => out.push({ page: page.pageNum, pali: p, sinh: sinh[i] }));
  }
  return out;
}

function select(text, flat) {
  let from;
  let to; // exclusive
  if (text.start.heading) {
    const want = normHeading(text.start.heading);
    const h = flat.findIndex((x) => x.pali.type === 'heading' && normHeading(x.pali.text) === want);
    if (h < 0) throw new Error(`${text.id}: heading "${want}" not found in ${text.file}`);
    if (flat.findIndex((x, i) => i > h && x.pali.type === 'heading' && normHeading(x.pali.text) === want) >= 0) {
      throw new Error(`${text.id}: heading "${want}" is not unique in ${text.file}`);
    }
    from = h + 1;
    const level = flat[h].pali.level || 1;
    to = flat.findIndex((x, i) => i > h && x.pali.type === 'heading' && (x.pali.level || 1) >= level);
    if (to < 0) to = flat.length;
  } else {
    from = flat.findIndex((x) => text.start.match.test(toPlain(x.pali.text)));
    if (from < 0) throw new Error(`${text.id}: start ${text.start.match} not found in ${text.file}`);
    to = flat.length;
  }
  if (text.end) {
    const re = text.end.match || text.end.before;
    const e = flat.findIndex((x, i) => i >= from && re.test(toPlain(x.pali.text)));
    if (e < 0) throw new Error(`${text.id}: end ${re} not found in ${text.file}`);
    to = text.end.match ? e + 1 : e;
  }
  let range = flat.slice(from, to);
  // a sutta at the end of a vagga is followed by the vagga's closing line and its uddāna (list of sutta names)
  const uddana = range.findIndex((x) => /^(තත්රුද්දානං|තස්සුද්දානං|උද්දානං)/.test(toPlain(x.pali.text).trim()));
  if (uddana >= 0) range = range.slice(0, uddana);
  const isTrailer = (x) => {
    const t = toPlain(x.pali.text).trim();
    return !t || isNumberLine(x.pali.text) || (x.pali.type === 'centered' && /වග්ගො/.test(t));
  };
  while (range.length && isTrailer(range[range.length - 1])) range.pop();
  return range;
}

// ---------------------------------------------------------------- markdown files

const yamlStr = (s) => JSON.stringify(s);

function setFrontmatterLine(md, key, value) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---/.exec(md);
  if (!m) throw new Error('no frontmatter');
  let fm = m[1];
  const line = `${key}: ${value}`;
  const re = new RegExp(`^${key}:.*$`, 'm');
  fm = re.test(fm) ? fm.replace(re, line) : `${fm}\n${line}`;
  return md.slice(0, m.index) + `---\n${fm}\n---` + md.slice(m.index + m[0].length);
}

function renderSide(range, side) {
  return range.map((x) => entryHtml(x[side])).filter(Boolean);
}

async function main() {
  const dry = process.argv.includes('--dry'); // print the selected ranges, write nothing
  const cache = new Map();
  const report = [];
  for (const text of TEXTS) {
    if (!cache.has(text.file)) cache.set(text.file, flatten(await loadFile(text.file)));
    const range = select(text, cache.get(text.file));
    const pali = renderSide(range, 'pali');
    const sinh = renderSide(range, 'sinh');
    const source = SOURCE_PREFIX + text.ref;
    const target = path.join(CONTENT_DIR, `${text.id}.md`);

    let md;
    if (text.existing) {
      md = fs.readFileSync(target, 'utf8');
      const at = md.indexOf(MARKER);
      if (at >= 0) md = md.slice(0, at);
      else if (!md.endsWith('\n')) md += '\n';
      md += `${MARKER}\n${TRANSLATION_NOTE}\n${sinh.join('\n')}\n`;
      md = setFrontmatterLine(md, 'order', text.order);
      md = setFrontmatterLine(md, 'source', yamlStr(source));
    } else {
      md = [
        '---',
        `title: ${yamlStr(text.title)}`,
        'keywords:',
        ...text.keywords.map((k) => `    - ${yamlStr(k)}`),
        'collections:',
        '    - "pirith"',
        `order: ${text.order}`,
        `source: ${yamlStr(source)}`,
        '---',
        GENERATED,
        ...pali,
        MARKER,
        ...sinh,
        '',
      ].join('\n');
    }
    if (dry) {
      const show = (x) => (x ? `[${x.type}] ${toPlain(x.text).replace(/\n/g, ' / ')}`.slice(0, 90) : '-');
      console.log(`\n== ${text.id} (${text.file})`);
      for (const x of [range[0], range[1], range[range.length - 2], range[range.length - 1]]) console.log(`  P ${show(x && x.pali)}\n  S ${show(x && x.sinh)}`);
    } else fs.writeFileSync(target, md);
    report.push(`${text.id.padEnd(34)} ${text.file.padEnd(9)} entries ${String(range.length).padStart(3)}  pali ${pali.length}  sinh ${sinh.length}`);
  }
  console.log(report.join('\n'));
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
